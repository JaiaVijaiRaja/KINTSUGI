def get_reconstruction_storage_path() -> Path:
    """Resolve and ensure the local reconstruction runs storage directory exists."""
    base = Path(settings.RECONSTRUCTION_STORAGE_DIR)
    if not base.is_absolute():
        cwd = Path.cwd()
        if (cwd / "backend").is_dir():
            base = cwd / "backend" / base
        else:
            base = cwd / base
    base.mkdir(parents=True, exist_ok=True)
    return base


class ReconstructionService:
    """Service orchestrating evidence-based signal reconstruction and audit record persistence."""

    def execute_reconstruction_run(
        self,
        pipeline_id: str,
        detection_run_id: str,
    ) -> ReconstructionRunResponse:
        """
        Execute confidence-aware reconstruction for all anomalies flagged in a detection run.
        Original source CSV remains strictly immutable.
        """
        start_time = datetime.now(timezone.utc).isoformat()
        rec_run_id = f"rec_run_{uuid.uuid4().hex[:12]}"
        logger.info(
            "Starting reconstruction run %s for pipeline '%s' and detection run '%s'",
            rec_run_id,
            pipeline_id,
            detection_run_id,
        )

        # 1. Retrieve and validate pipeline configuration
        pipeline_cfg = pipeline_service.get_pipeline_config(pipeline_id)

        # 2. Retrieve and validate detection run
        det_run = detection_service.get_detection_run(detection_run_id)
        if det_run.configuration_id != pipeline_id:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"Detection run '{detection_run_id}' was generated by configuration '{det_run.configuration_id}', not '{pipeline_id}'.",
            )
        if det_run.status not in ["completed", "partial_failure"]:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"Detection run '{detection_run_id}' has status '{det_run.status}'; only completed runs can be reconstructed.",
            )

        # 3. Retrieve detection run anomalies
        det_results = detection_service.get_detection_run_results(detection_run_id, limit=50000, offset=0)
        anomaly_records = det_results.anomalies

        # 4. Load actual stored source CSV dataset
        dataset_storage = get_storage_path()
        csv_path = dataset_storage / det_run.dataset_id / "data.csv"
        if not csv_path.exists():
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"Source CSV file for dataset '{det_run.dataset_id}' not found.",
            )

        try:
            df = pd.read_csv(csv_path)
        except Exception as e:
            logger.exception("Failed to read CSV %s: %s", csv_path, str(e))
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail=f"Failed to read source CSV dataset: {str(e)}",
            )

        # 5. Build lookup maps for anomalies by sensor column
        anomaly_map: Dict[str, Set[int]] = {}
        for col in pipeline_cfg.sensor_columns:
            anomaly_map[col] = set()

        for anom in anomaly_records:
            if anom.sensor_column in anomaly_map:
                anomaly_map[anom.sensor_column].add(anom.source_row_index)

        # Resolve timestamp series if configured
        timestamp_series: Optional[pd.Series] = None
        if pipeline_cfg.timestamp_column and pipeline_cfg.timestamp_column in df.columns:
            timestamp_series = df[pipeline_cfg.timestamp_column]

        # Also identify unmeasured/missing cells (NaN/null) in sensor columns to evaluate for reconstruction
        eval_targets: List[AnomalyRecord] = list(anomaly_records)
        existing_targets = {(a.sensor_column, a.source_row_index) for a in anomaly_records}

        for col in pipeline_cfg.sensor_columns:
            if col in df.columns:
                series_vals_raw = df[col]
                for r_idx in range(len(df)):
                    val_at_r = series_vals_raw.iloc[r_idx]
                    if pd.isna(val_at_r) or not np.isfinite(val_at_r):
                        if (col, r_idx) not in existing_targets:
                            ts_str = str(timestamp_series.iloc[r_idx]) if (timestamp_series is not None and pd.notna(timestamp_series.iloc[r_idx])) else None
                            missing_rec = AnomalyRecord(
                                anomaly_id=f"anom_missing_{col}_{r_idx}",
                                run_id=det_run.run_id,
                                dataset_id=det_run.dataset_id,
                                configuration_id=pipeline_id,
                                sensor_column=col,
                                source_row_index=r_idx,
                                timestamp=ts_str,
                                original_value=None,
                                detector_name="missing_value_check",
                                detector_score=None,
                                detection_reason="Missing observation (NaN/null): packet drop, sensor offline, or transmission loss",
                                severity="HIGH",
                                flagged_status="FLAGGED",
                                consensus="SINGLE_DETECTOR",
                                detectors_flagged=["missing_value_check"],
                                detector_details={},
                            )
                            eval_targets.append(missing_rec)
                            existing_targets.add((col, r_idx))
                            if col in anomaly_map:
                                anomaly_map[col].add(r_idx)

        # Sort evaluation targets deterministically by (source_row_index, sensor_column)
        eval_targets.sort(key=lambda x: (x.source_row_index, x.sensor_column))

        reconstruction_records: List[ReconstructionRecord] = []
        errors: List[str] = []
        warnings: List[str] = []

        rec_settings = pipeline_cfg.reconstruction_settings
        max_gap = rec_settings.max_gap_size

        # 6. Evaluate reconstruction for each flagged anomaly and missing observation
        for anom in eval_targets:
            col = anom.sensor_column
            if col not in df.columns:
                continue

            target_idx = anom.source_row_index
            if target_idx < 0 or target_idx >= len(df):
                continue

            raw_val_item = df[col].iloc[target_idx]
            try:
                orig_val: Optional[float] = float(raw_val_item) if pd.notnull(raw_val_item) else None
            except (ValueError, TypeError):
                orig_val = None

            series_vals = df[col].to_numpy(dtype=float, na_value=np.nan)
            col_anom_indices = anomaly_map.get(col, set())

            # Method A: Linear Interpolation
            interp_val, interp_refs, interp_reason, interp_valid = reconstruct_linear_interpolation(
                values=series_vals,
                target_idx=target_idx,
                timestamps=timestamp_series,
                max_gap_size=max_gap,
                anomaly_indices=col_anom_indices,
                sensor_column=col,
            )

            # Method B: Local Median Reconstruction
            median_val, median_refs, median_reason, median_valid = reconstruct_local_median(
                values=series_vals,
                target_idx=target_idx,
                timestamps=timestamp_series,
                window_radius=5,
                min_observations=3,
                anomaly_indices=col_anom_indices,
                sensor_column=col,
            )

            # Determine primary candidate proposal
            primary_method = "none"
            proposed_val: Optional[float] = None
            evidence_summary = ""
            primary_refs = []
            is_structurally_valid = False
            structural_reason: Optional[str] = None
            is_safety_violation = False

            if rec_settings.allow_linear_interpolation:
                if interp_valid:
                    primary_method = "linear_interpolation"
                    proposed_val = interp_val
                    evidence_summary = interp_reason
                    primary_refs = interp_refs
                    is_structurally_valid = True
                else:
                    # Check if interpolation failed due to hard safety constraints:
                    # 1. Boundary extrapolation prohibition
                    # 2. Maximum gap limit exceeded
                    is_safety_violation = (
                        "extrapolation is strictly prohibited" in interp_reason.lower()
                        or "exceeds configured maximum gap limit" in interp_reason.lower()
                    )
                    if is_safety_violation or rec_settings.fallback_behavior == "abstain_unresolved":
                        primary_method = "none"
                        proposed_val = None
                        is_structurally_valid = False
                        structural_reason = interp_reason
                        evidence_summary = structural_reason
                    elif median_valid:
                        primary_method = "local_median"
                        proposed_val = median_val
                        evidence_summary = median_reason
                        primary_refs = median_refs
                        is_structurally_valid = True
                    else:
                        primary_method = "none"
                        proposed_val = None
                        is_structurally_valid = False
                        structural_reason = interp_reason
                        evidence_summary = structural_reason
            elif median_valid:
                primary_method = "local_median"
                proposed_val = median_val
                evidence_summary = median_reason
                primary_refs = median_refs
                is_structurally_valid = True
            else:
                primary_method = "none"
                proposed_val = None
                is_structurally_valid = False
                structural_reason = median_reason
                evidence_summary = structural_reason

            # Method C: Cross-Sensor Validation
            cross_val, cross_agree, cross_adj, cross_refs, cross_summary = evaluate_cross_sensor_validation(
                df=df,
                target_sensor=col,
                target_idx=target_idx,
                candidate_val=proposed_val,
                anomaly_map=anomaly_map,
            )

            # If interpolation and median were impossible, can cross-sensor establish a proposal?
            if not is_structurally_valid and not is_safety_violation and cross_val is not None and cross_agree is True:
                primary_method = "cross_sensor"
                proposed_val = cross_val
                is_structurally_valid = True
                evidence_summary = cross_summary
                primary_refs = cross_refs

            # Calculate local signal dispersion around target
            w_start = max(0, target_idx - 5)
            w_end = min(len(df), target_idx + 6)
            local_window_vals = [
                series_vals[k] for k in range(w_start, w_end)
                if k != target_idx and k not in col_anom_indices and np.isfinite(series_vals[k])
            ]
            local_std = float(np.std(local_window_vals)) if len(local_window_vals) > 1 else 0.0
            local_mean = float(np.mean(local_window_vals)) if len(local_window_vals) > 0 else 0.0

            # Count anomalous neighbors in surrounding radius
            surrounding_anoms = sum(
                1 for k in range(w_start, w_end)
                if k != target_idx and k in col_anom_indices
            )

            interp_gap_len = None
            if interp_refs and len(interp_refs) == 2:
                interp_gap_len = int(abs(interp_refs[1].source_row_index - interp_refs[0].source_row_index) - 1)

            # Compute evidence-based confidence score (0 to 100)
            confidence_breakdown = calculate_reconstruction_confidence(
                interp_val=interp_val if interp_valid else None,
                interp_gap=interp_gap_len,
                median_val=median_val if median_valid else None,
                neighbor_count=len(local_window_vals),
                min_neighbors_required=3,
                local_std=local_std,
                local_mean=local_mean,
                surrounding_anomaly_count=surrounding_anoms,
                cross_sensor_agreement=cross_agree,
                cross_sensor_adjustment=cross_adj,
                is_valid_proposal=is_structurally_valid,
                invalid_reason=structural_reason,
            )

            has_conflict = (cross_agree is False)

            # Evaluate acceptance policy
            status_tag, final_val, policy_reason = evaluate_reconstruction_policy(
                original_val=orig_val,
                proposed_val=proposed_val,
                confidence_score=confidence_breakdown.total_score,
                pipeline_config=pipeline_cfg,
                is_structurally_valid=is_structurally_valid,
                structural_failure_reason=structural_reason,
                has_evidence_conflict=has_conflict,
            )

            # Combine all evidence references
            combined_evidence = primary_refs.copy()
            for cr in cross_refs:
                if not any(r.sensor_column == cr.sensor_column and r.source_row_index == cr.source_row_index for r in combined_evidence):
                    combined_evidence.append(cr)

            rec_record = ReconstructionRecord(
                result_id=f"rec_res_{uuid.uuid4().hex[:12]}",
                reconstruction_run_id=rec_run_id,
                detection_run_id=detection_run_id,
                anomaly_id=anom.anomaly_id,
                dataset_id=det_run.dataset_id,
                configuration_id=pipeline_id,
                sensor_column=col,
                source_row_index=target_idx,
                timestamp=anom.timestamp,
                original_value=orig_val,
                proposed_value=proposed_val,
                final_value=final_val,
                method=primary_method,  # type: ignore[arg-type]
                status=status_tag,
                confidence_score=confidence_breakdown.total_score,
                confidence_breakdown=confidence_breakdown,
                evidence_summary=evidence_summary,
                evidence_references=combined_evidence,
                abstention_reason=policy_reason if status_tag == "UNRESOLVED" else None,
                is_reviewed=False,
                created_at=datetime.now(timezone.utc).isoformat(),
            )
            reconstruction_records.append(rec_record)

        # 7. Compute Run Summary
        total_eval = len(reconstruction_records)
        measured_cnt = sum(1 for r in reconstruction_records if r.status == "MEASURED")
        estimated_cnt = sum(1 for r in reconstruction_records if r.status == "ESTIMATED")
        corrected_cnt = sum(1 for r in reconstruction_records if r.status == "CORRECTED")
        unresolved_cnt = sum(1 for r in reconstruction_records if r.status == "UNRESOLVED")
        avg_conf = (
            float(np.mean([r.confidence_score for r in reconstruction_records]))
            if total_eval > 0
            else 0.0
        )

        by_sensor: Dict[str, Dict[str, int]] = {}
        for s in pipeline_cfg.sensor_columns:
            by_sensor[s] = {"CORRECTED": 0, "ESTIMATED": 0, "UNRESOLVED": 0, "MEASURED": 0}

        by_method: Dict[str, int] = Counter([r.method for r in reconstruction_records])

        for r in reconstruction_records:
            if r.sensor_column not in by_sensor:
                by_sensor[r.sensor_column] = {"CORRECTED": 0, "ESTIMATED": 0, "UNRESOLVED": 0, "MEASURED": 0}
            by_sensor[r.sensor_column][r.status] = by_sensor[r.sensor_column].get(r.status, 0) + 1

        summary = ReconstructionSummary(
            total_evaluated=total_eval,
            measured_count=measured_cnt,
            estimated_count=estimated_cnt,
            corrected_count=corrected_cnt,
            unresolved_count=unresolved_cnt,
            average_confidence=round(avg_conf, 2),
            anomalies_reconstructed_count=corrected_cnt,
            by_sensor=by_sensor,
            by_method=dict(by_method),
        )

        completion_time = datetime.now(timezone.utc).isoformat()

        run_obj = ReconstructionRun(
            reconstruction_run_id=rec_run_id,
            detection_run_id=detection_run_id,
            pipeline_id=pipeline_id,
            dataset_id=det_run.dataset_id,
            configuration_version=pipeline_cfg.configuration_version,
            status="completed",
            start_time=start_time,
            completion_time=completion_time,
            summary=summary,
            errors=errors,
            warnings=warnings,
        )

        # 8. Atomic Disk Persistence
        rec_storage = get_reconstruction_storage_path()
        run_dir = rec_storage / rec_run_id
        temp_dir = rec_storage / f".tmp_{rec_run_id}"

        try:
            if temp_dir.exists():
                shutil.rmtree(temp_dir)
            temp_dir.mkdir(parents=True, exist_ok=True)

            with open(temp_dir / "run.json", "w", encoding="utf-8") as f:
                json.dump(run_obj.model_dump(), f, indent=2)

            with open(temp_dir / "results.json", "w", encoding="utf-8") as f:
                json.dump([r.model_dump() for r in reconstruction_records], f, indent=2)

            # Atomic rename commit with Windows retry & fallback
            committed = False
            for attempt in range(5):
                try:
                    if run_dir.exists():
                        shutil.rmtree(run_dir)
                    temp_dir.rename(run_dir)
                    committed = True
                    break
                except (PermissionError, OSError):
                    time.sleep(0.05 * (attempt + 1))

            if not committed:
                try:
                    shutil.copytree(temp_dir, run_dir, dirs_exist_ok=True)
                    shutil.rmtree(temp_dir, ignore_errors=True)
                except Exception:
                    if run_dir.exists():
                        shutil.rmtree(run_dir, ignore_errors=True)
                    raise

            logger.info("Successfully persisted reconstruction run %s with %d records", rec_run_id, len(reconstruction_records))

            try:
                from app.services.audit_service import audit_service
                from app.schemas.audit import AuditEventType

                audit_service.record_event(
                    AuditEventType.RECONSTRUCTION_RUN_STARTED,
                    reconstruction_run_id=rec_run_id,
                    detection_run_id=detection_run_id,
                    pipeline_id=pipeline_id,
                    dataset_id=det_run.dataset_id,
                    custom_timestamp=start_time,
                    decision_reason="Reconstruction run started.",
                )
                for r in reconstruction_records:
                    evt_t = (
                        AuditEventType.CORRECTION_ACCEPTED
                        if r.status == "CORRECTED"
                        else AuditEventType.RECONSTRUCTION_UNRESOLVED
                        if r.status == "UNRESOLVED"
                        else AuditEventType.VALUE_PROPOSED
                    )
                    audit_service.record_event(
                        evt_t,
                        reconstruction_run_id=rec_run_id,
                        reconstruction_result_id=r.result_id,
                        detection_run_id=detection_run_id,
                        pipeline_id=pipeline_id,
                        dataset_id=det_run.dataset_id,
                        source_row_index=r.source_row_index,
                        sensor_column=r.sensor_column,
                        original_value=r.original_value,
                        proposed_value=r.proposed_value,
                        final_value=r.final_value,
                        new_status=r.status,
                        reconstruction_method=r.method,
                        confidence_score=r.confidence_score,
                        decision_reason=r.abstention_reason or f"Reconstruction committed with status {r.status}.",
                        custom_timestamp=completion_time,
                    )
                audit_service.record_event(
                    AuditEventType.RECONSTRUCTION_RUN_COMPLETED,
                    reconstruction_run_id=rec_run_id,
                    detection_run_id=detection_run_id,
                    pipeline_id=pipeline_id,
                    dataset_id=det_run.dataset_id,
                    processing_outcome="completed",
                    custom_timestamp=completion_time,
                    decision_reason=f"Reconstruction completed: {corrected_cnt} corrected, {unresolved_cnt} unresolved.",
                )
            except Exception as audit_err:
                logger.warning("Failed to record audit events for reconstruction run %s: %s", rec_run_id, str(audit_err))
        except Exception as e:
            if temp_dir.exists():
                shutil.rmtree(temp_dir, ignore_errors=True)
            logger.exception("Failed to atomically persist reconstruction run %s: %s", rec_run_id, str(e))
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail=f"Failed to persist reconstruction run: {str(e)}",
            )

        return ReconstructionRunResponse(
            run=run_obj,
            sample_results=reconstruction_records[:5],
        )

    def list_reconstruction_runs(
        self,
        pipeline_id: Optional[str] = None,
        detection_run_id: Optional[str] = None,
        limit: int = 50,
        offset: int = 0,
    ) -> ReconstructionRunListResponse:
        """List historical reconstruction runs from persistent disk storage."""
        rec_storage = get_reconstruction_storage_path()
        runs: List[ReconstructionRun] = []

        if rec_storage.exists():
            for item in sorted(rec_storage.iterdir(), key=lambda p: p.stat().st_mtime, reverse=True):
                if item.is_dir() and item.name.startswith("rec_run_"):
                    run_file = item / "run.json"
                    results_file = item / "results.json"
                    if run_file.exists() and results_file.exists():
                        try:
                            with open(run_file, "r", encoding="utf-8") as f:
                                data = json.load(f)
                                r_run = ReconstructionRun(**data)
                                if pipeline_id and r_run.pipeline_id != pipeline_id:
                                    continue
                                if detection_run_id and r_run.detection_run_id != detection_run_id:
                                    continue
                                runs.append(r_run)
                        except Exception as e:
                            logger.warning("Corrupted reconstruction run file %s: %s", run_file, str(e))

        bounded_limit = min(max(1, limit), 500)
        bounded_offset = max(0, offset)
        sliced = runs[bounded_offset : bounded_offset + bounded_limit]

        return ReconstructionRunListResponse(
            runs=sliced,
            total=len(runs),
        )

    def get_reconstruction_run(self, reconstruction_run_id: str) -> ReconstructionRun:
        """Lookup metadata and summary for a single reconstruction run."""
        rec_storage = get_reconstruction_storage_path()
        run_file = rec_storage / reconstruction_run_id / "run.json"

        if not run_file.exists():
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"Reconstruction run '{reconstruction_run_id}' not found.",
            )

        try:
            with open(run_file, "r", encoding="utf-8") as f:
                data = json.load(f)
                return ReconstructionRun(**data)
        except Exception as e:
            logger.exception("Failed to read reconstruction run %s: %s", run_file, str(e))
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail=f"Failed to read reconstruction run '{reconstruction_run_id}'.",
            )

    def get_reconstruction_results(
        self,
        reconstruction_run_id: str,
        sensor_column: Optional[str] = None,
        status: Optional[str] = None,
        limit: int = 50,
        offset: int = 0,
    ) -> ReconstructionResultsResponse:
        """Retrieve paginated reconstruction records with filtering by sensor channel and processing status."""
        run = self.get_reconstruction_run(reconstruction_run_id)
        rec_storage = get_reconstruction_storage_path()
        results_file = rec_storage / reconstruction_run_id / "results.json"

        if not results_file.exists():
            return ReconstructionResultsResponse(
                reconstruction_run_id=run.reconstruction_run_id,
                detection_run_id=run.detection_run_id,
                pipeline_id=run.pipeline_id,
                dataset_id=run.dataset_id,
                summary=run.summary,
                total_results=0,
                results=[],
                limit=limit,
                offset=offset,
            )

        try:
            with open(results_file, "r", encoding="utf-8") as f:
                raw_list = json.load(f)
                records = [ReconstructionRecord(**r) for r in raw_list]
        except Exception as e:
            logger.exception("Failed to read results %s: %s", results_file, str(e))
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail=f"Failed to read reconstruction results for run '{reconstruction_run_id}'.",
            )

        # Apply filters
        filtered: List[ReconstructionRecord] = []
        for rec in records:
            if sensor_column and rec.sensor_column != sensor_column:
                continue
            if status and rec.status != status.upper():
                continue
            filtered.append(rec)

        bounded_limit = min(max(1, limit), 500)
        bounded_offset = max(0, offset)
        sliced = filtered[bounded_offset : bounded_offset + bounded_limit]

        return ReconstructionResultsResponse(
            reconstruction_run_id=run.reconstruction_run_id,
            detection_run_id=run.detection_run_id,
            pipeline_id=run.pipeline_id,
            dataset_id=run.dataset_id,
            summary=run.summary,
            total_results=len(filtered),
            results=sliced,
            limit=bounded_limit,
            offset=bounded_offset,
        )

    def get_result_by_id(self, result_id: str) -> ReconstructionRecord:
        """Lookup a specific reconstruction record across stored runs."""
        rec_storage = get_reconstruction_storage_path()
        if rec_storage.exists():
            for r_dir in rec_storage.iterdir():
                if r_dir.is_dir() and r_dir.name.startswith("rec_run_"):
                    results_file = r_dir / "results.json"
                    if results_file.exists():
                        try:
                            with open(results_file, "r", encoding="utf-8") as f:
                                data = json.load(f)
                                for item in data:
                                    if item.get("result_id") == result_id:
                                        return ReconstructionRecord(**item)
                        except Exception:
                            continue

        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Reconstruction record with ID '{result_id}' not found.",
        )

    def review_result(
        self,
        result_id: str,
        decision_req: ReviewDecisionRequest,
    ) -> ReconstructionRecord:
        """
        Record an operator review decision on a candidate signal repair.
        Transitions:
        - ACCEPT: status -> CORRECTED, final_value -> proposed_value (or modified_value)
        - REJECT: status -> UNRESOLVED, final_value -> original_value
        - MODIFY: status -> CORRECTED, final_value -> modified_value
        """
        rec_storage = get_reconstruction_storage_path()
        now_str = datetime.now(timezone.utc).isoformat()

        if rec_storage.exists():
            for r_dir in rec_storage.iterdir():
                if r_dir.is_dir() and r_dir.name.startswith("rec_run_"):
                    results_file = r_dir / "results.json"
                    run_file = r_dir / "run.json"

                    if results_file.exists():
                        try:
                            with open(results_file, "r", encoding="utf-8") as f:
                                data = json.load(f)

                            target_index: Optional[int] = None
                            for idx, item in enumerate(data):
                                if item.get("result_id") == result_id:
                                    target_index = idx
                                    break

                            if target_index is not None:
                                target_rec = ReconstructionRecord(**data[target_index])

                                # Apply Review Decision Transition
                                if decision_req.decision == "ACCEPT":
                                    if target_rec.proposed_value is None:
                                        raise HTTPException(
                                            status_code=status.HTTP_400_BAD_REQUEST,
                                            detail="Cannot accept a reconstruction result that has no proposed value.",
                                        )
                                    target_rec.status = "CORRECTED"
                                    target_rec.final_value = (
                                        decision_req.modified_value
                                        if decision_req.modified_value is not None
                                        else target_rec.proposed_value
                                    )
                                elif decision_req.decision == "REJECT":
                                    target_rec.status = "UNRESOLVED"
                                    target_rec.final_value = target_rec.original_value
                                    target_rec.abstention_reason = (
                                        f"Human operator rejected candidate proposal: {decision_req.review_comment or 'No comment provided'}"
                                    )
                                elif decision_req.decision == "MODIFY":
                                    if decision_req.modified_value is None or not np.isfinite(decision_req.modified_value):
                                        raise HTTPException(
                                            status_code=status.HTTP_400_BAD_REQUEST,
                                            detail="Decision MODIFY requires a valid finite modified_value.",
                                        )
                                    target_rec.status = "CORRECTED"
                                    target_rec.final_value = decision_req.modified_value

                                target_rec.is_reviewed = True
                                target_rec.reviewed_by = decision_req.reviewer_name
                                target_rec.review_decision = decision_req.decision
                                target_rec.review_comment = decision_req.review_comment
                                target_rec.reviewed_at = now_str

                                data[target_index] = target_rec.model_dump()

                                # Update results.json atomically
                                tmp_results = r_dir / ".tmp_results.json"
                                with open(tmp_results, "w", encoding="utf-8") as f:
                                    json.dump(data, f, indent=2)
                                tmp_results.replace(results_file)

                                # Update summary in run.json
                                if run_file.exists():
                                    with open(run_file, "r", encoding="utf-8") as f:
                                        run_data = json.load(f)
                                    all_recs = [ReconstructionRecord(**r) for r in data]
                                    run_data["summary"]["measured_count"] = sum(1 for r in all_recs if r.status == "MEASURED")
                                    run_data["summary"]["estimated_count"] = sum(1 for r in all_recs if r.status == "ESTIMATED")
                                    run_data["summary"]["corrected_count"] = sum(1 for r in all_recs if r.status == "CORRECTED")
                                    run_data["summary"]["unresolved_count"] = sum(1 for r in all_recs if r.status == "UNRESOLVED")
                                    run_data["summary"]["anomalies_reconstructed_count"] = run_data["summary"]["corrected_count"]

                                    tmp_run = r_dir / ".tmp_run.json"
                                    with open(tmp_run, "w", encoding="utf-8") as f:
                                        json.dump(run_data, f, indent=2)
                                    tmp_run.replace(run_file)

                                try:
                                    from app.services.audit_service import audit_service
                                    from app.schemas.audit import AuditEventType

                                    rev_evt = (
                                        AuditEventType.REVIEW_APPROVED
                                        if decision_req.decision == "ACCEPT"
                                        else AuditEventType.REVIEW_REJECTED
                                        if decision_req.decision == "REJECT"
                                        else AuditEventType.REVIEW_COMMENT_ADDED
                                    )
                                    audit_service.record_event(
                                        rev_evt,
                                        reconstruction_run_id=target_rec.reconstruction_run_id,
                                        reconstruction_result_id=target_rec.result_id,
                                        detection_run_id=target_rec.detection_run_id,
                                        source_row_index=target_rec.source_row_index,
                                        sensor_column=target_rec.sensor_column,
                                        original_value=target_rec.original_value,
                                        proposed_value=target_rec.proposed_value,
                                        final_value=target_rec.final_value,
                                        new_status=target_rec.status,
                                        confidence_score=target_rec.confidence_score,
                                        decision_reason=f"Operator '{decision_req.reviewer_name}' submitted '{decision_req.decision}': {decision_req.review_comment or 'No comment'}",
                                        custom_timestamp=now_str,
                                    )
                                except Exception as audit_err:
                                    logger.warning("Failed to record review audit event: %s", str(audit_err))

                                return target_rec
                        except HTTPException:
                            raise
                        except Exception as e:
                            logger.exception("Error reviewing result %s in %s: %s", result_id, r_dir.name, str(e))
                            raise HTTPException(
                                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                                detail=f"Failed to commit review decision: {str(e)}",
                            )

        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Reconstruction record with ID '{result_id}' not found.",
        )

    def export_reconstructed_dataset(
        self,
        reconstruction_run_id: str,
        format_type: str = "csv",
    ) -> Tuple[str, str]:
        """
        Export complete dataset incorporating verified signal reconstructions and provenance status columns.
        Preserves original raw telemetry columns while adding transparent status and repaired value columns.
        Returns: (file_content_str, media_type)
        """
        rec_run = self.get_reconstruction_run(reconstruction_run_id)
        results = self.get_reconstruction_results(reconstruction_run_id, limit=50000, offset=0).results

        # Load original raw dataset CSV
        dataset_storage = get_storage_path()
        csv_path = dataset_storage / rec_run.dataset_id / "data.csv"
        if not csv_path.exists():
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail=f"Source CSV dataset for run '{reconstruction_run_id}' not found at {csv_path}.",
            )

        try:
            df = pd.read_csv(csv_path)
        except Exception as e:
            logger.exception("Failed to load source CSV %s: %s", csv_path, str(e))
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail=f"Failed to read source CSV dataset: {str(e)}",
            )

        # Build mapping of (sensor_col, row_index) -> ReconstructionRecord
        repairs_by_cell: Dict[Tuple[str, int], ReconstructionRecord] = {}
        affected_sensors = set()
        for r in results:
            repairs_by_cell[(r.sensor_column, r.source_row_index)] = r
            affected_sensors.add(r.sensor_column)

        # Build output dataframe
        export_df = df.copy()

        # For every sensor column that has any reconstruction evaluated:
        for sensor in sorted(list(affected_sensors)):
            if sensor not in export_df.columns:
                continue

            repaired_col = f"{sensor}_repaired"
            status_col = f"{sensor}_status"
            method_col = f"{sensor}_method"
            confidence_col = f"{sensor}_confidence"

            repaired_vals = []
            status_vals = []
            method_vals = []
            confidence_vals = []

            for row_idx in range(len(export_df)):
                cell_key = (sensor, row_idx)
                if cell_key in repairs_by_cell:
                    rec = repairs_by_cell[cell_key]
                    final_val = rec.final_value if rec.status in ["CORRECTED", "ESTIMATED"] else rec.original_value
                    repaired_vals.append(final_val)
                    status_vals.append(rec.status)
                    method_vals.append(rec.method)
                    confidence_vals.append(round(rec.confidence_score, 1))
                else:
                    orig_val = export_df.at[row_idx, sensor]
                    is_missing = pd.isna(orig_val)
                    repaired_vals.append(orig_val)
                    status_vals.append("UNRESOLVED" if is_missing else "MEASURED")
                    method_vals.append("none")
                    confidence_vals.append(None)

            export_df[repaired_col] = repaired_vals
            export_df[status_col] = status_vals
            export_df[method_col] = method_vals
            export_df[confidence_col] = confidence_vals

        if format_type.lower() == "csv":
            buf = io.StringIO()
            export_df.to_csv(buf, index=False)
            return buf.getvalue(), "text/csv"
        elif format_type.lower() == "json":
            return export_df.to_json(orient="records", indent=2), "application/json"
        else:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"Unsupported export format '{format_type}'. Expected 'csv' or 'json'.",
            )


